import {
  storyPageSidesFor,
  type StoryPageLayout,
  type StoryPageSides,
} from "./story-page-sides.ts";

export type StoryPage = {
  src: string;
  audioSrc: string | null;
  transcript: string;
  layout: StoryPageLayout;
  sides: StoryPageSides | null;
};

export type ListenTask = {
  prompt: string;
  audioText: string;
  choices: string[];
  correctAnswer: string;
};

export type SpeakTask = {
  modelLine: string;
  tip: string;
};

export type ReadTask = {
  passage: string;
  question: string;
  choices: string[];
  correctAnswer: string;
};

export type WriteTask = {
  modelSentence: string;
  targetWords: string[];
};

export type BookTasks = {
  listen: ListenTask;
  speak: SpeakTask;
  read: ReadTask;
  write: WriteTask;
};

export type Book = {
  slug: string;
  title: string;
  cover: string;
  colour: string;
  focus: string[];
  level: 1 | 2 | 3;
  term: 1 | 2 | 3 | 4;
  unit: number;
  pages: StoryPage[];
  tasks: BookTasks;
};

const makePages = (slug: string, transcripts: string[]): StoryPage[] =>
  transcripts.map((transcript, index) => ({
    src: `/pages/${slug}/${String(index + 1).padStart(2, "0")}.webp`,
    audioSrc: transcript.trim()
      ? `/audio/${slug}/${String(index + 1).padStart(2, "0")}.mp3`
      : null,
    transcript,
    ...storyPageSidesFor(slug, index, transcript),
  }));

